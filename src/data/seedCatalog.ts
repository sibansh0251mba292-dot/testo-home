export async function seedInitialCatalogIfAdmin(): Promise<void> {
  try {
    const configRef = doc(db, 'settings', 'operations');
    const configSnap = await getDoc(configRef);
    if (configSnap.exists()) {
      return;
    }

    await setDoc(configRef, {
      ...DEFAULT_OPERATIONAL_CONFIG,
      updatedAt: serverTimestamp(),
    });

    await Promise.all([
      ...DEFAULT_TESTS.map((t) =>
        setDoc(doc(db, 'tests', t.id), {
          name: t.name,
          nameHi: t.nameHi || '',
          category: t.category,
          shortDescription: t.shortDescription,
          shortDescriptionHi: t.shortDescriptionHi || '',
          price: t.price,
          discountedPrice: t.discountedPrice,
          isDemoPrice: t.isDemoPrice,
          preparation: t.preparation,
          preparationHi: t.preparationHi || '',
          fastingRequired: t.fastingRequired,
          fastingHours: t.fastingHours || 0,
          reportDeliveryHours: t.reportDeliveryHours,
          sampleType: t.sampleType || '',
          isPopular: Boolean(t.isPopular),
          active: t.active,
          updatedAt: serverTimestamp(),
        })
      ),
      ...DEFAULT_PACKAGES.map((p) =>
        setDoc(doc(db, 'packages', p.id), {
          name: p.name,
          nameHi: p.nameHi || '',
          tagline: p.tagline || '',
          description: p.description,
          descriptionHi: p.descriptionHi || '',
          includedTests: p.includedTests,
          testCount: p.testCount,
          price: p.price,
          discountedPrice: p.discountedPrice,
          isDemoPrice: p.isDemoPrice,
          fastingRequired: p.fastingRequired,
          fastingHours: p.fastingHours || 0,
          reportDeliveryHours: p.reportDeliveryHours,
          isRecommended: Boolean(p.isRecommended),
          active: p.active,
          updatedAt: serverTimestamp(),
        })
      ),
      ...DEFAULT_OFFERS.map((o) =>
        setDoc(doc(db, 'offers', o.id), {
          title: o.title,
          titleHi: o.titleHi || '',
          code: o.code,
          discountPercent: o.discountPercent,
          maxDiscount: o.maxDiscount,
          description: o.description,
          active: o.active,
          updatedAt: serverTimestamp(),
        })
      ),
      ...DEFAULT_PINCODES.map((pin) =>
        setDoc(doc(db, 'serviceable_pincodes', pin.pincode), {
          pincode: pin.pincode,
          city: pin.city,
          area: pin.area,
          serviceFee: pin.serviceFee,
          active: pin.active,
          updatedAt: serverTimestamp(),
        })
      ),
      ...DEFAULT_SLOTS.map((slot) =>
        setDoc(doc(db, 'time_slots', slot.id), {
          label: slot.label,
          startTime: slot.startTime,
          endTime: slot.endTime,
          maxBookings: slot.maxBookings,
          active: slot.active,
          updatedAt: serverTimestamp(),
        })
      ),
      ...DEFAULT_PHLEBOTOMISTS.map((phleb) =>
        setDoc(doc(db, 'phlebotomists', phleb.id), {
          name: phleb.name,
          phone: phleb.phone,
          certificationCode: phleb.certificationCode,
          zonePincodes: phleb.zonePincodes,
          active: phleb.active,
          updatedAt: serverTimestamp(),
        })
      ),
    ]);
  } catch (error) {
    handleFirestoreError(error, OperationType.WRITE, 'settings/operations');
  }
}
